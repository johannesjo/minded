#!/usr/bin/env node
// Regenerates src/shared/sky/timeZoneCoordinates.ts from the system tzdata
// (zone1970.tab + zone.tab for coordinates, tzdata.zi for backward-compatible
// link names such as Asia/Calcutta or US/Eastern, which some engines still
// report from Intl). Coordinates are rounded to whole degrees: the sky only
// needs to know roughly where the sun is - a degree of longitude is four
// minutes of solar time, well inside what a zone's own width already blurs.
//
//   node scripts/generate-timezone-coordinates.mjs [/usr/share/zoneinfo]
import { readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const zoneinfo = process.argv[2] ?? "/usr/share/zoneinfo";
const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../src/shared/sky/timeZoneCoordinates.ts");

// ±DDMM[SS]±DDDMM[SS] → [lat, lon] in decimal degrees.
const parseIso6709 = (s) => {
  const m = s.match(
    /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/,
  );
  if (!m) throw new Error(`bad coordinates ${s}`);
  const deg = (sign, d, mm, ss) =>
    (sign === "-" ? -1 : 1) *
    (Number(d) + Number(mm) / 60 + Number(ss ?? 0) / 3600);
  return [deg(m[1], m[2], m[3], m[4]), deg(m[5], m[6], m[7], m[8])];
};

const coords = new Map();
for (const file of ["zone.tab", "zone1970.tab"]) {
  for (const line of readFileSync(resolve(zoneinfo, file), "utf8").split(
    "\n",
  )) {
    if (!line || line.startsWith("#")) continue;
    const [, c, zone] = line.split("\t");
    coords.set(zone, parseIso6709(c));
  }
}
// Links: "L <target> <alias>". Only aliases whose target has coordinates;
// Etc/* and the bare UTC/GMT names stay unknown on purpose (no location).
for (const line of readFileSync(resolve(zoneinfo, "tzdata.zi"), "utf8").split(
  "\n",
)) {
  if (!line.startsWith("L ")) continue;
  const [, target, alias] = line.split(" ");
  if (coords.has(target) && !coords.has(alias))
    coords.set(alias, coords.get(target));
}

const entries = [...coords.entries()]
  .map(([z, [lat, lon]]) => `${z},${Math.round(lat)},${Math.round(lon)}`)
  .sort();

const body = `// GENERATED by scripts/generate-timezone-coordinates.mjs from tzdata
// (zone1970.tab, zone.tab, tzdata.zi links) - do not edit by hand.
//
// IANA zone -> the zone's principal location, whole degrees. Packed as one
// "Zone,lat,lon;..." string so the table stays a few KB in every bundle.
export const TIME_ZONE_COORDINATES_PACKED =
  ${JSON.stringify(entries.join(";"))};
`;
writeFileSync(out, body);
console.log(`wrote ${entries.length} zones to ${out}`);

// The native home-screen widgets time their sun to the same table (the app's
// WebView isn't running when they repaint), so they get verbatim copies.
// widgetSolarMirror.test.ts fails if a copy drifts from the TS one.
const packed = JSON.stringify(entries.join(";"));
const repoRoot = resolve(here, "../..");
const nativeOuts = [
  [
    resolve(
      repoRoot,
      "android/app/src/main/java/com/minded/minded/widget/WidgetTimeZones.kt",
    ),
    `// GENERATED by extension/scripts/generate-timezone-coordinates.mjs - do not edit
// by hand. The Kotlin copy of extension/src/shared/sky/timeZoneCoordinates.ts.
package com.minded.minded.widget

/**
 * IANA zone -> the zone's principal location, whole degrees: roughly where the
 * user is, from the time zone alone (no permission, no network). Unknown zones
 * (UTC, the Etc zones) return null and the widget falls back to the fixed clock.
 */
object WidgetTimeZones {
    private const val PACKED =
        ${packed}

    private val table: Map<String, WidgetSun.LatLon> by lazy {
        PACKED.split(";").associate { entry ->
            val (zone, lat, lon) = entry.split(",")
            zone to WidgetSun.LatLon(lat.toDouble(), lon.toDouble())
        }
    }

    fun locationFor(zone: String?): WidgetSun.LatLon? = zone?.let { table[it] }
}
`,
  ],
  [
    resolve(repoRoot, "extension/ios/App/MindedWidget/WidgetTimeZones.swift"),
    `// GENERATED by extension/scripts/generate-timezone-coordinates.mjs - do not edit
// by hand. The Swift copy of extension/src/shared/sky/timeZoneCoordinates.ts.

import Foundation

/// IANA zone -> the zone's principal location, whole degrees: roughly where the
/// user is, from the time zone alone (no permission, no network). Unknown zones
/// (UTC, the Etc zones) return nil and the widget falls back to the fixed clock.
enum WidgetTimeZones {
    private static let packed =
        ${packed}

    private static let table: [String: WidgetSun.LatLon] = {
        var table: [String: WidgetSun.LatLon] = [:]
        for entry in packed.split(separator: ";") {
            let parts = entry.split(separator: ",")
            guard parts.count == 3, let lat = Double(parts[1]), let lon = Double(parts[2]) else {
                continue
            }
            table[String(parts[0])] = WidgetSun.LatLon(lat: lat, lon: lon)
        }
        return table
    }()

    static func location(for zone: String?) -> WidgetSun.LatLon? {
        guard let zone = zone else { return nil }
        return table[zone]
    }
}
`,
  ],
];
for (const [file, source] of nativeOuts) {
  writeFileSync(file, source);
  console.log(`wrote ${file}`);
}
