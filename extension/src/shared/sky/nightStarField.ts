/**
 * The resting night sky's hand-placed star field, as data - and the twilight
 * that brings it out.
 *
 * The field itself is the `--night-stars` SVG in _variables.scss (see the long
 * note there on density and distribution); that copy stays the no-JS default,
 * and nightStarField.test.ts pins this list to it star for star. What this
 * module adds is the order they appear in: real stars don't arrive as a whole
 * sky at once - the brightest show first, a few minutes after sunset, and the
 * faint ones only once the twilight has fully drained. So the live sky rebuilds
 * the same SVG with each star faded by how deep the twilight is
 * (starDepth from solarSky.ts), brightest first, and reaches the full field
 * only in true (astronomical) night.
 *
 * It is ambient *state*, applied per minute like every other sky value - each
 * star takes ~a fifth of the twilight to come in, so a minute's step is a
 * few percent of one pinpoint's brightness and nothing visibly moves. No
 * animation, so prefers-reduced-motion has nothing to stop here.
 */

