type FieldStar = {
  cx: string;
  cy: string;
  r: string;
  opacity: string;
  /** 0 brightest .. 1 faintest - when in the twilight this star comes out. */
  rank: number;
};

let field: FieldStar[] | null = null;
const getField = (): FieldStar[] => {
  if (field) return field;
  const stars = PACKED_STARS.split(";").map((s) => {
    const [cx, cy, r, opacity] = s.split(",");
    return { cx, cy, r, opacity, rank: 0 };
  });
  // Apparent brightness ~ area x opacity. Stable sort on ties keeps it
  // deterministic.
  const order = stars
    .map((s, i) => ({ i, b: Number(s.r) ** 2 * Number(s.opacity) }))
    .sort((a, b) => b.b - a.b || a.i - b.i);
  order.forEach(({ i }, pos) => {
    stars[i].rank = order.length > 1 ? pos / (order.length - 1) : 0;
  });
  field = stars;
  return field;
};

/** How much of the twilight one star takes to come fully in. */
const STAR_FADE_SPAN = 0.2;

/** 0..1: how far this star has come out at the given twilight depth. */
export const starVisibilityAt = (rank: number, depth: number): number => {
  if (depth >= 1) return 1; // true night: every star, exactly
  const start = rank * (1 - STAR_FADE_SPAN);
  return Math.min(1, Math.max(0, (depth - start) / STAR_FADE_SPAN));
};

/** How many stars the field holds. */
export const nightStarCount = (): number => getField().length;

const circle = (s: FieldStar, opacity: string): string =>
  `<circle cx='${s.cx}' cy='${s.cy}' r='${s.r}' opacity='${opacity}'/>`;

/**
 * The `--night-stars` layer at a twilight depth (0 = none out yet, 1 = true
 * night): a CSS `url(...)` value, or `none` before the first star. At depth 1
 * this is byte-identical to the stylesheet's field.
 */
export const nightStarsLayerAt = (depth: number): string => {
  if (depth <= 0) return "none";
  const d = Math.min(1, depth);
  let body = "";
  for (const s of getField()) {
    const v = starVisibilityAt(s.rank, d);
    if (v <= 0) continue;
    body += circle(
      s,
      v >= 1
        ? s.opacity
        : String(Math.round(Number(s.opacity) * v * 100) / 100),
    );
  }
  return body ? `url("${SVG_OPEN}${body}${SVG_CLOSE}")` : "none";
};
